"""
Data models for the Attention module.

Defines strongly typed containers for attention-enhanced feature maps
produced by the EMA Attention module.

Author: Ishita Dutta
Project: UIFAF
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Tuple

import torch

from backbone.backbone_models import FeatureMap
from .exceptions import (
    InvalidAttentionFeatureError,
    InvalidAttentionOutputError,
)


# ---------------------------------------------------------
# Attention Feature Map
# ---------------------------------------------------------


@dataclass(frozen=True)
class AttentionFeatureMap(FeatureMap):
    """
    Represents one attention-enhanced feature map.

    Attributes
    ----------
    attention_map : torch.Tensor | None
        Spatial attention map generated by EMA.

    attention_name : str
        Name of attention mechanism.
    """

    attention_map: torch.Tensor | None = None

    attention_name: str = "EMA"

    def validate(self) -> None:
        """
        Validate attention feature map.
        """

        super().validate()

        if self.attention_map is not None:

            if not isinstance(
                self.attention_map,
                torch.Tensor,
            ):
                raise InvalidAttentionFeatureError(
                    f"{self.stage}: attention_map must be torch.Tensor."
                )

            if self.attention_map.ndim != 4:
                raise InvalidAttentionFeatureError(
                    f"{self.stage}: attention_map must be 4D."
                )

            if (
                self.attention_map.shape[0]
                != self.tensor.shape[0]
            ):
                raise InvalidAttentionFeatureError(
                    f"{self.stage}: batch size mismatch."
                )

            if (
                self.attention_map.shape[2:]
                != self.tensor.shape[2:]
            ):
                raise InvalidAttentionFeatureError(
                    f"{self.stage}: spatial size mismatch."
                )


# ---------------------------------------------------------
# Attention Output
# ---------------------------------------------------------


@dataclass
class AttentionOutput:
    """
    Complete output of the EMA Attention module.
    """

    stage1: AttentionFeatureMap

    stage2: AttentionFeatureMap

    stage3: AttentionFeatureMap

    stage4: AttentionFeatureMap

    # (height, width)
    original_size: Tuple[int, int]

    def validate(self) -> None:
        """
        Validate every stage.
        """

        self.stage1.validate()
        self.stage2.validate()
        self.stage3.validate()
        self.stage4.validate()

        h, w = self.original_size

        if h <= 0 or w <= 0:
            raise InvalidAttentionOutputError(
                "Invalid original image size."
            )

    @property
    def stages(self):
        """
        Returns all attention stages.
        """

        return (
            self.stage1,
            self.stage2,
            self.stage3,
            self.stage4,
        )

    @property
    def num_stages(self) -> int:
        return 4

    @property
    def stage_names(self):
        return (
            self.stage1.stage,
            self.stage2.stage,
            self.stage3.stage,
            self.stage4.stage,
        )
